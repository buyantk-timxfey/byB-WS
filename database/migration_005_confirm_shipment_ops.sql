/* Перевод зависших операций "Закупка" (привязанных к поставке) из pending в confirmed.
   С 06.06 поставка создавала операцию со статусом pending, из-за чего она не отображалась
   в ленте "Операции" и не влияла на баланс. Условие без кириллицы надёжно выделяет
   именно закупки поставок (shipment_id задан, sale_id пуст), продажи не трогает.
   Идемпотентно. ВАЖНО: файл не должен начинаться с "--" — deploy.php отбрасывает такие стейтменты. */
UPDATE bank_operations
SET status = 'confirmed'
WHERE status = 'pending'
  AND shipment_id IS NOT NULL
  AND sale_id IS NULL;
